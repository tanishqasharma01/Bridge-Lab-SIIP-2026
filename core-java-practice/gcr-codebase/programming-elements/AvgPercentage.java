public class AvgPercentage {
    public static void main(String[] args) {
        int marks1 = 94;
        int marks2 =95;
        int marks3 =96;
        int totalMarks = marks1+marks2+marks3;
        double percentage = (totalMarks/3)*100;
        System.out.println("Average percentage: " + percentage + "%");
    }
    
}
